"""Documentation-only organization; preserve runtime bytes and generated assets."""
import hashlib,json,re
from pathlib import Path

root=Path(__file__).resolve().parents[2]
folder=root/'landing_training';backup=Path(__file__).parent
before=json.loads((backup/'before.json').read_text())
def sha(p):return hashlib.sha256(p.read_bytes()).hexdigest()
def within(p):p.resolve().relative_to(root.resolve());return p
def exclusive(path,data):
    within(path);path.parent.mkdir(parents=True,exist_ok=True)
    with path.open('xb') as f:f.write(data)

old_readme=folder/'README.md'
assert old_readme.read_bytes()==(backup/'README.md').read_bytes()
report=folder/'LANDING_POLICY_DEVELOPMENT_REPORT_2026-10-17.md'
target=folder/'docs/reports'/report.name
assert report.read_bytes()==(backup/report.name).read_bytes()
assert not target.exists();within(target);target.parent.mkdir(parents=True,exist_ok=True)
report.rename(target)

original=old_readme.read_text(encoding='utf-8')
links=re.findall(r'\]\(([^)]+)\)',original)
assert set(links)=={'outputs/stress_review/index.html','outputs/stress_review/speed_report.json','outputs/review_bundle/index.html','collection_benchmark.py','schema.json'}
historical=re.sub(r'\]\(([^)]+)\)',lambda m:'](../../'+m.group(1)+')',original)
intro='''> **Historical baseline guide.** This preserves the original environment-review
> documentation and its original training workflow. Statements such as “no trained
> weights” describe that earlier stage, not the current project. The wave/speed
> ranges below are historical experiment settings, not the latest qualification.
> Start with the [current overview](../../README.md) and
> [current policy reference](../CURRENT_POLICY.md).
>
> Commands still run from the repository root. Historical `outputs/` links require
> the original generated review bundles; those are not present in this Windows copy.

'''
exclusive(folder/'docs/history/ENVIRONMENT_REVIEW_BASELINE.md',(intro+historical).encode())

# Only verified interpreter-generated bytecode is discarded. Never recursively
# remove an unknown directory or classify experiment output as scratch.
cache=within(folder/'__pycache__')
removed=[]
if cache.exists():
    entries=list(cache.iterdir())
    assert all(p.is_file() and re.fullmatch(r'[A-Za-z0-9_]+\.cpython-312\.pyc',p.name) for p in entries)
    hashes={r['path']:r['sha256'] for r in before}
    for p in entries:
        assert sha(p)==hashes[p.relative_to(folder).as_posix()]
        removed.append(p.relative_to(folder).as_posix());p.unlink()
    cache.rmdir()
(backup/'changes.json').write_text(json.dumps({'report_move':{'from':report.relative_to(folder).as_posix(),'to':target.relative_to(folder).as_posix()},'readme_backup':'README.md','historical_guide':'docs/history/ENVIRONMENT_REVIEW_BASELINE.md','removed_generated_bytecode':removed},indent=2)+'\n')
print('Moved report without changing its contents; archived baseline guide; removed',len(removed),'verified bytecode files.')
